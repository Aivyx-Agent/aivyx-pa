    #[test]
    fn unauthenticated_hint_only_when_configured_but_no_tokens() {
        let tmp = std::env::temp_dir().join(format!("aivyx-hint-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&tmp).unwrap();
        let cmd = "/opt/bin/aivyx-gmail";
        // No tokens.json → hint names the fix.
        let hint = unauthenticated_hint(cmd, &tmp).expect("hint");
        assert!(hint.contains("aivyx-pa connect gmail"));
        // A non-service command → no hint.
        assert!(unauthenticated_hint("/usr/bin/ripgrep", &tmp).is_none());
        // Once tokens.json exists → no hint.
        let g = find_service("gmail").unwrap();
        std::fs::create_dir_all(g.process_dir(&tmp)).unwrap();
        std::fs::write(g.token_path(&tmp), "{}").unwrap();
        assert!(unauthenticated_hint(cmd, &tmp).is_none());
        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn write_then_connected_check_round_trips() {
        let tmp = std::env::temp_dir().join(format!("aivyx-connect-{}", uuid::Uuid::new_v4()));
        let svc = find_service("calendar").unwrap();
        // Not connected before, and no config yet.
        assert!(!svc.is_connected(&tmp));
        let path = write_oauth_config(svc, &tmp, "the-id", "the-secret").unwrap();
        assert!(path.exists());
        let body = std::fs::read_to_string(&path).unwrap();
        assert!(body.contains("client_id = \"the-id\""));
        assert!(body.contains("127.0.0.1:8766")); // calendar's port
        // Still "not connected" — config exists but no tokens.json.
        assert!(!svc.is_connected(&tmp));
        // Simulate a successful auth init writing tokens.json.
        std::fs::write(svc.token_path(&tmp), "{}").unwrap();
        assert!(svc.is_connected(&tmp));
        let _ = std::fs::remove_dir_all(&tmp);
    }

