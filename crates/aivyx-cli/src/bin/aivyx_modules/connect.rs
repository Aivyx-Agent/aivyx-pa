/// Find the operator's `aivyx-pa.toml`: CWD first (where the wizard
/// writes), then `~/.config/aivyx-pa/aivyx-pa.toml`.
pub fn find_aivyx_toml(home: &Path) -> Option<PathBuf> {
    let cwd = std::env::current_dir().ok().map(|d| d.join("aivyx-pa.toml"));
    if let Some(p) = &cwd {
        if p.exists() {
            return cwd;
        }
    }
    let xdg = home.join(".config").join("aivyx-pa").join("aivyx-pa.toml");
    if xdg.exists() { Some(xdg) } else { None }
}

/// Is a `[[tool_process]]` with this `name` already present?
pub fn tool_process_present(doc: &toml_edit::DocumentMut, name: &str) -> bool {
    doc.get("tool_process")
        .and_then(|i| i.as_array_of_tables())
        .map(|arr| {
            arr.iter()
                .any(|t| t.get("name").and_then(|v| v.as_str()) == Some(name))
        })
        .unwrap_or(false)
}

/// Append a `[[tool_process]]` entry (name + command) to the doc,
/// preserving everything else. Caller checks
/// [`tool_process_present`] first.
pub fn append_tool_process(doc: &mut toml_edit::DocumentMut, name: &str, command: &str) {
    use toml_edit::{Item, Table, value};
    let mut t = Table::new();
    t["name"] = value(name);
    t["command"] = value(command);
    let entry = doc
        .entry("tool_process")
        .or_insert_with(|| Item::ArrayOfTables(Default::default()));
    if let Some(aot) = entry.as_array_of_tables_mut() {
        aot.push(t);
    }
}

fn offer_tool_process_wiring(
    reader: &mut dyn BufRead,
    writer: &mut dyn Write,
    svc: &ConnectService,
    binary: &Path,
) -> Result<(), String> {
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_default();
    let Some(toml_path) = find_aivyx_toml(&home) else {
        writeln!(
            writer,
            "\nAdd this to your aivyx-pa.toml to enable the tool:\n\n\
             [[tool_process]]\nname = \"{}\"\ncommand = \"{}\"",
            svc.key,
            binary.display()
        )
        .map_err(|e| format!("write error: {e}"))?;
        return Ok(());
    };

    let body = std::fs::read_to_string(&toml_path)
        .map_err(|e| format!("read {}: {e}", toml_path.display()))?;
    let mut doc: toml_edit::DocumentMut = body
        .parse()
        .map_err(|e| format!("parse {}: {e}", toml_path.display()))?;
    if tool_process_present(&doc, svc.key) {
        writeln!(
            writer,
            "Your aivyx-pa.toml already has a `{}` tool — you're all set.",
            svc.key
        )
        .map_err(|e| format!("write error: {e}"))?;
        return Ok(());
    }
    if !prompt_yes_no(
        &format!(
            "Add a [[tool_process]] entry for {} to {}?",
            svc.display,
            toml_path.display()
        ),
        true,
        reader,
        writer,
    )? {
        return Ok(());
    }
    append_tool_process(&mut doc, svc.key, &binary.to_string_lossy());
    std::fs::write(&toml_path, doc.to_string())
        .map_err(|e| format!("write {}: {e}", toml_path.display()))?;
    writeln!(
        writer,
        "Added `{}` to {}. Restart the daemon to load it.",
        svc.key,
        toml_path.display()
    )
    .map_err(|e| format!("write error: {e}"))?;
    Ok(())
}

