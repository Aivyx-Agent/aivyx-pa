//! Chapter Mise (MI.1) — `aivyx-pa connect kitchen`.
//!
//! The kitchen vertical's one-command setup. Unlike the Google services in
//! [`connect`](super::connect) this is **non-OAuth**: the kitchen toolkit
//! authenticates to KitchenDB (PostgREST) with a `base_url` + `api_key` +
//! `organization_id`, not a consent dance. So `connect kitchen` routes here,
//! reusing `connect`'s generic helpers (`append_tool_process`,
//! `tool_process_present`, `find_aivyx_toml`, `write_file_at_0600`, the
//! prompts) but
//! writing the `[kitchen_db]` config (Brigade BG.1), planting the bundled BOH
//! pack + `[team] config_path` (Roster), and **probing KitchenDB reachability**
//! in place of the OAuth handshake. Every step is idempotent + no-clobber.

use std::io::{BufRead, Write};
use std::path::{Path, PathBuf};

use aivyx_kitchen::KITCHEN_BOH_TOML;
use aivyx_kitchen_toolkit::KitchenClient;

use super::connect::{
    append_tool_process, find_aivyx_toml, prompt_line, tool_process_present, write_file_at_0600,
};

const KITCHEN_BINARY: &str = "aivyx-kitchen-toolkit";
/// The reachability-probe RPC — a cheap, side-effect-free read (Mise OQ-3).
const PROBE_FN: &str = "get_suppliers";
/// The planted pack filename, beside `aivyx-pa.toml` (Mise OQ-1).
const PACK_FILENAME: &str = "kitchen-boh.toml";

/// `~/.aivyx-pa/tool-processes/kitchen/`.
fn process_dir(home: &Path) -> PathBuf {
    home.join(".aivyx-pa").join("tool-processes").join("kitchen")
}

fn config_path(home: &Path) -> PathBuf {
    process_dir(home).join("config.toml")
}

/// Render the `[kitchen_db]` config the toolkit loads (Brigade BG.1 shape).
pub fn render_kitchen_config_toml(base_url: &str, api_key: &str, organization_id: &str) -> String {
    format!(
        "# Generated by `aivyx-pa connect kitchen`. KitchenDB (PostgREST) connection.\n\
         # api_key is sensitive; this file is written 0600.\n\
         [kitchen_db]\n\
         base_url = \"{}\"\n\
         api_key = \"{}\"\n\
         organization_id = \"{}\"\n",
        escape(base_url),
        escape(api_key),
        escape(organization_id),
    )
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Write the kitchen `config.toml` (0600). Returns the path.
pub fn write_kitchen_config(
    home: &Path,
    base_url: &str,
    api_key: &str,
    organization_id: &str,
) -> Result<PathBuf, String> {
    let dir = process_dir(home);
    std::fs::create_dir_all(&dir)
        .map_err(|e| format!("failed to create {}: {e}", dir.display()))?;
    let path = config_path(home);
    let body = render_kitchen_config_toml(base_url, api_key, organization_id);
    write_file_at_0600(&path, body.as_bytes())
        .map_err(|e| format!("failed to write {}: {e}", path.display()))?;
    Ok(path)
}

/// Set `[team] config_path = <pack>` **only if absent** (never clobber an
/// operator's existing team config). Returns whether it was set.
pub fn set_team_config_path_if_absent(doc: &mut toml_edit::DocumentMut, pack: &str) -> bool {
    let existing = doc
        .get("team")
        .and_then(|t| t.get("config_path"))
        .and_then(|v| v.as_str())
        .map(str::trim)
        .filter(|s| !s.is_empty());
    if existing.is_some() {
        return false;
    }
    // Create the table explicitly first — indexing a missing table into
    // existence makes toml_edit render an INLINE `team = { … }` at the
    // root (valid but ugly; found by the Freight install smoke).
    if doc.get("team").is_none() {
        doc["team"] = toml_edit::Item::Table(toml_edit::Table::new());
    }
    doc["team"]["config_path"] = toml_edit::value(pack);
    true
}

/// Probe KitchenDB reachability with one cheap read. `Ok(n)` = number of rows
/// the probe RPC returned (an array); a typed, actionable error otherwise.
pub async fn probe_kitchen_db(
    base_url: &str,
    api_key: &str,
    organization_id: &str,
) -> Result<usize, String> {
    let client = KitchenClient::new(reqwest::Client::new(), base_url, api_key, organization_id);
    match client.call_rpc(PROBE_FN, serde_json::json!({})).await {
        Ok(serde_json::Value::Array(rows)) => Ok(rows.len()),
        Ok(_) => Ok(0), // reachable, non-array body (still a successful round-trip)
        Err(e) => Err(format!(
            "could not reach KitchenDB ({e}). Check base_url, api_key, and \
             organization_id in {}.",
            "~/.aivyx-pa/tool-processes/kitchen/config.toml",
        )),
    }
}

/// `aivyx-pa connect kitchen` entry. Interactive on a TTY; for headless installs,
/// supply `AIVYX_PA_KITCHEN_BASE_URL` / `AIVYX_PA_KITCHEN_API_KEY` /
/// `AIVYX_PA_KITCHEN_ORGANIZATION_ID` and the prompts are skipped.
pub async fn run_connect_kitchen(
    reader: &mut dyn BufRead,
    writer: &mut dyn Write,
    home: &Path,
) -> Result<(), String> {
    writeln!(
        writer,
        "Connecting the Kitchen vertical (KitchenDB / PostgREST).\n"
    )
    .map_err(werr)?;

    let base_url = field(
        "AIVYX_PA_KITCHEN_BASE_URL",
        "KitchenDB base URL (e.g. https://…/rest/v1): ",
        reader,
        writer,
    )?;
    let api_key = field(
        "AIVYX_PA_KITCHEN_API_KEY",
        "KitchenDB API key: ",
        reader,
        writer,
    )?;
    let organization_id = field(
        "AIVYX_PA_KITCHEN_ORGANIZATION_ID",
        "Organization id (tenant): ",
        reader,
        writer,
    )?;
    if base_url.is_empty() || api_key.is_empty() || organization_id.is_empty() {
        return Err("base_url, api_key, and organization_id are all required".to_string());
    }

    // 1. config.toml (0600).
    let cfg = write_kitchen_config(home, &base_url, &api_key, &organization_id)?;
    writeln!(writer, "Wrote {} (0600).", cfg.display()).map_err(werr)?;

    // 2-3. tool_process + pack + team config_path into aivyx-pa.toml.
    if let Some(toml_path) = find_aivyx_toml(home) {
        wire_aivyx_toml(&toml_path, home, writer)?;
    } else {
        writeln!(
            writer,
            "\nNo aivyx-pa.toml found. Add this, then `aivyx-pa team init --pack {PACK_FILENAME}`:\n\n\
             [[tool_process]]\nname = \"kitchen\"\ncommand = \"{KITCHEN_BINARY}\"\n\n[team]\nconfig_path = \"{PACK_FILENAME}\""
        )
        .map_err(werr)?;
    }

    // 4. Reachability probe — the "connected" signal for a non-OAuth service.
    match probe_kitchen_db(&base_url, &api_key, &organization_id).await {
        Ok(n) => {
            writeln!(writer, "\n✓ KitchenDB reachable ({n} supplier(s) visible). Restart the daemon to load the kitchen tools.").map_err(werr)?;
            Ok(())
        }
        Err(hint) => {
            writeln!(writer, "\n✗ {hint}\nThe config was saved; fix it and re-run `aivyx-pa connect kitchen` to re-check.").map_err(werr)?;
            Err("KitchenDB not reachable".to_string())
        }
    }
}

/// Plant the pack + wire `[[tool_process]]` + `[team] config_path` into the
/// found `aivyx-pa.toml`, idempotently. The pack is written beside it.
fn wire_aivyx_toml(toml_path: &Path, home: &Path, writer: &mut dyn Write) -> Result<(), String> {
    // Plant the bundled BOH pack beside aivyx-pa.toml (no-clobber).
    let pack_path = toml_path.parent().unwrap_or(home).join(PACK_FILENAME);
    if pack_path.exists() {
        writeln!(writer, "Kept existing {}.", pack_path.display()).map_err(werr)?;
    } else {
        std::fs::write(&pack_path, KITCHEN_BOH_TOML)
            .map_err(|e| format!("write {}: {e}", pack_path.display()))?;
        writeln!(writer, "Planted the BOH pack at {}.", pack_path.display()).map_err(werr)?;
    }

    let body = std::fs::read_to_string(toml_path)
        .map_err(|e| format!("read {}: {e}", toml_path.display()))?;
    let mut doc: toml_edit::DocumentMut = body
        .parse()
        .map_err(|e| format!("parse {}: {e}", toml_path.display()))?;

    if tool_process_present(&doc, "kitchen") {
        writeln!(
            writer,
            "aivyx-pa.toml already wires the `kitchen` tool process."
        )
        .map_err(werr)?;
    } else {
        append_tool_process(&mut doc, "kitchen", KITCHEN_BINARY);
        writeln!(writer, "Wired [[tool_process]] kitchen → {KITCHEN_BINARY}.").map_err(werr)?;
    }
    if set_team_config_path_if_absent(&mut doc, PACK_FILENAME) {
        writeln!(writer, "Set [team] config_path = \"{PACK_FILENAME}\".").map_err(werr)?;
    } else {
        writeln!(writer, "Kept your existing [team] config_path.").map_err(werr)?;
    }
    std::fs::write(toml_path, doc.to_string())
        .map_err(|e| format!("write {}: {e}", toml_path.display()))?;
    Ok(())
}

/// Read a field from its env var, else prompt for it (trimmed).
fn field(
    env: &str,
    prompt: &str,
    reader: &mut dyn BufRead,
    writer: &mut dyn Write,
) -> Result<String, String> {
    if let Some(v) = std::env::var_os(env) {
        let v = v.to_string_lossy().trim().to_string();
        if !v.is_empty() {
            return Ok(v);
        }
    }
    prompt_line(prompt, reader, writer)
}

fn werr(e: std::io::Error) -> String {
    format!("write error: {e}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_config_has_kitchen_db_section_and_escapes() {
        let s = render_kitchen_config_toml("https://k/rest/v1", "KEY\"x", "ORG");
        assert!(s.contains("[kitchen_db]"));
        assert!(s.contains("base_url = \"https://k/rest/v1\""));
        assert!(s.contains("api_key = \"KEY\\\"x\""), "{s}");
        assert!(s.contains("organization_id = \"ORG\""));
    }

    #[test]
    fn config_round_trips_into_the_toolkit_loader() {
        // The rendered config must parse via the toolkit's own loader.
        let dir = std::env::temp_dir().join(format!("mise-cfg-{}", std::process::id()));
        std::fs::create_dir_all(dir.join(".aivyx-pa/tool-processes/kitchen")).unwrap();
        let p = write_kitchen_config(&dir, "https://k/rest/v1", "KEY", "ORG").unwrap();
        let loaded = aivyx_kitchen_toolkit::load_config(&p).unwrap();
        assert_eq!(loaded.base_url, "https://k/rest/v1");
        assert_eq!(loaded.organization_id, "ORG");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[cfg(unix)]
    #[test]
    fn write_kitchen_config_is_0600() {
        use std::os::unix::fs::PermissionsExt;
        let dir = std::env::temp_dir().join(format!("mise-mode-{}", std::process::id()));
        std::fs::create_dir_all(dir.join(".aivyx-pa/tool-processes/kitchen")).unwrap();
        let p = write_kitchen_config(&dir, "https://k/rest/v1", "KEY", "ORG").unwrap();
        let mode = std::fs::metadata(&p).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o600);
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn team_config_path_set_only_when_absent() {
        let mut doc: toml_edit::DocumentMut = "".parse().unwrap();
        assert!(set_team_config_path_if_absent(&mut doc, "kitchen-boh.toml"));
        assert_eq!(
            doc["team"]["config_path"].as_str(),
            Some("kitchen-boh.toml")
        );
        // No-clobber: a second call (now present) leaves it.
        assert!(!set_team_config_path_if_absent(&mut doc, "other.toml"));
        assert_eq!(
            doc["team"]["config_path"].as_str(),
            Some("kitchen-boh.toml")
        );
    }

    #[test]
    fn team_config_path_respects_an_existing_value() {
        let mut doc: toml_edit::DocumentMut =
            "[team]\nconfig_path = \"mine.toml\"\n".parse().unwrap();
        assert!(!set_team_config_path_if_absent(
            &mut doc,
            "kitchen-boh.toml"
        ));
        assert_eq!(doc["team"]["config_path"].as_str(), Some("mine.toml"));
    }
}
