    /// Grab a free localhost port by binding then dropping a listener.
    async fn free_port() -> u16 {
        tokio::net::TcpListener::bind("127.0.0.1:0")
            .await
            .unwrap()
            .local_addr()
            .unwrap()
            .port()
    }

    async fn http_roundtrip(port: u16, request: &str) -> String {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let mut s = tokio::net::TcpStream::connect(("127.0.0.1", port))
            .await
            .unwrap();
        s.write_all(request.as_bytes()).await.unwrap();
        s.flush().await.unwrap();
        let mut buf = Vec::new();
        let _ =
            tokio::time::timeout(std::time::Duration::from_secs(3), s.read_to_end(&mut buf)).await;
        String::from_utf8_lossy(&buf).into_owned()
    }

    #[tokio::test]
    async fn server_enforces_auth_token_end_to_end() {
        let port = free_port().await;
        let shutdown = CancellationToken::new();
        let server_shutdown = shutdown.clone();
        // socket_path is only touched AFTER auth passes (on a real /ws bridge),
        // so a bogus path is fine for the rejection assertions here.
        let handle = tokio::spawn(async move {
            let _ = run_web_ui_server(
                PathBuf::from("/nonexistent/aivyx-postern-test.sock"),
                Some(std::net::IpAddr::V4(std::net::Ipv4Addr::LOCALHOST)),
                port,
                Vec::new(),
                Some("tok-abc123".to_string()),
                None,
                server_shutdown,
                None,
            )
            .await;
        });
        // Give the listener a moment to bind.
        tokio::time::sleep(std::time::Duration::from_millis(150)).await;

        // (1) Static request with NO credentials → 401 + Basic challenge.
        let resp = http_roundtrip(port, "GET / HTTP/1.1\r\nHost: x\r\n\r\n").await;
        assert!(
            resp.starts_with("HTTP/1.1 401"),
            "no-auth static: {resp:.60}"
        );
        assert!(
            resp.contains("WWW-Authenticate: Basic"),
            "must challenge: {resp:.120}"
        );

        // (2) Static request WITH the Basic password → 200 + Set-Cookie.
        use base64::Engine;
        let creds = base64::engine::general_purpose::STANDARD.encode("u:tok-abc123");
        let ok = http_roundtrip(
            port,
            &format!("GET / HTTP/1.1\r\nHost: x\r\nAuthorization: Basic {creds}\r\n\r\n"),
        )
        .await;
        assert!(ok.starts_with("HTTP/1.1 200"), "authed static: {ok:.60}");
        assert!(
            ok.contains(&format!("Set-Cookie: {AUTH_COOKIE}=tok-abc123")),
            "must plant the cookie for the /ws upgrade",
        );

        // (3) /ws upgrade with NO cookie/creds → 401 (control plane closed).
        let ws = http_roundtrip(
            port,
            "GET /ws HTTP/1.1\r\nHost: x\r\nOrigin: http://127.0.0.1\r\nUpgrade: websocket\r\n\r\n",
        )
        .await;
        assert!(
            ws.starts_with("HTTP/1.1 401"),
            "unauth /ws must be 401: {ws:.60}"
        );

        shutdown.cancel();
        let _ = handle.await;
    }

    #[tokio::test]
    async fn classic_route_is_gone() {
        // /classic used to serve the legacy multi-pane inspector (HTML::as_bytes())
        // with a 200. With that route removed, the path falls through
        // `serve_static`'s asset lookup like any other unknown path, which
        // returns a real "404 Not Found" status line — not a redirect, not the
        // legacy HTML, and not the `/`-fallback page either.
        let port = free_port().await;
        let shutdown = CancellationToken::new();
        let server_shutdown = shutdown.clone();
        let handle = tokio::spawn(async move {
            let _ = run_web_ui_server(
                PathBuf::from("/nonexistent/aivyx-classic-retirement-test.sock"),
                Some(std::net::IpAddr::V4(std::net::Ipv4Addr::LOCALHOST)),
                port,
                Vec::new(),
                None, // no auth token — isolate this test to routing, not Postern
                None,
                server_shutdown,
                None,
            )
            .await;
        });
        tokio::time::sleep(std::time::Duration::from_millis(150)).await;

        let resp = http_roundtrip(port, "GET /classic HTTP/1.1\r\nHost: x\r\n\r\n").await;
        assert!(
            resp.starts_with("HTTP/1.1 404"),
            "/classic must 404 now that the route is gone: {resp:.120}"
        );

        shutdown.cancel();
        let _ = handle.await;
    }
