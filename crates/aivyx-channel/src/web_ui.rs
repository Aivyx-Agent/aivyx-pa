/// Cookie name the browser carries back on the `/ws` upgrade (it cannot set
/// request headers on `new WebSocket()`, but same-origin cookies ARE sent on
/// the handshake). Planted on the Basic-Auth'd page load.
const AUTH_COOKIE: &str = "aivyx_web_token";

/// Constant-time byte comparison — avoids leaking the token length/prefix via
/// early-exit timing on a shared secret.
///
/// `pub(crate)` so `webhook_listener.rs`'s bearer-secret auth can reuse this
/// exact implementation rather than duplicating the compare logic (Task 1,
/// 2026-09-16 audit).
pub(crate) fn ct_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

/// First value of a header (case-insensitive name) from a peeked request head.
fn header_value<'a>(request_head: &'a str, name: &str) -> Option<&'a str> {
    request_head.split("\r\n").find_map(|line| {
        line.split_once(':')
            .and_then(|(n, v)| n.trim().eq_ignore_ascii_case(name).then(|| v.trim()))
    })
}

/// `Authorization: Bearer <token>` (non-browser clients).
fn bearer_token(request_head: &str) -> Option<&str> {
    header_value(request_head, "authorization")?
        .strip_prefix("Bearer ")
        .map(str::trim)
}

/// The password half of `Authorization: Basic base64(user:pass)` — how a
/// browser sends the token after the native Basic-Auth prompt.
fn basic_password(request_head: &str) -> Option<String> {
    use base64::Engine;
    let b64 = header_value(request_head, "authorization")?.strip_prefix("Basic ")?;
    let decoded = base64::engine::general_purpose::STANDARD
        .decode(b64.trim())
        .ok()?;
    let creds = String::from_utf8(decoded).ok()?;
    // user:pass — the token is the password (user is ignored).
    creds.split_once(':').map(|(_, pass)| pass.to_string())
}

/// The [`AUTH_COOKIE`] value from the `Cookie` header, if present.
fn cookie_token(request_head: &str) -> Option<String> {
    let cookies = header_value(request_head, "cookie")?;
    cookies.split(';').find_map(|kv| {
        let (k, v) = kv.split_once('=')?;
        (k.trim() == AUTH_COOKIE).then(|| v.trim().to_string())
    })
}

/// True when the request presents the valid token by ANY accepted means:
/// a Bearer header, HTTP Basic password, or the auth cookie.
fn request_carries_token(request_head: &str, token: &str) -> bool {
    let tb = token.as_bytes();
    if bearer_token(request_head).is_some_and(|t| ct_eq(t.as_bytes(), tb)) {
        return true;
    }
    if basic_password(request_head).is_some_and(|p| ct_eq(p.as_bytes(), tb)) {
        return true;
    }
    if cookie_token(request_head).is_some_and(|c| ct_eq(c.as_bytes(), tb)) {
        return true;
    }
    false
}

/// VITRINE.md §0 P2 — a stale saved credential (a browser's saved
/// Basic-Auth password, an old `Authorization: Bearer` value) used to
/// fail completely silently: no client-side "wrong token" indication
/// (the native prompt just re-appears) and nothing in the daemon
/// journal either — the operator needed a packet capture to diagnose.
/// Logs one line per rejecting IP per cooldown window rather than
/// once per request, since a browser that keeps re-submitting the same
/// stale saved value can retry many times per second.
const REJECTED_TOKEN_LOG_COOLDOWN: std::time::Duration = std::time::Duration::from_secs(60);

/// The decision logic, split out from `log_rejected_token_once`'s
/// `eprintln!` side effect so it's directly unit-testable: true (and
/// records `now` against `ip`) the first time `ip` is seen, or once
/// `REJECTED_TOKEN_LOG_COOLDOWN` has elapsed since it was last logged;
/// false otherwise.
fn should_log_rejected_token(
    map: &Mutex<std::collections::HashMap<std::net::IpAddr, std::time::Instant>>,
    ip: std::net::IpAddr,
    now: std::time::Instant,
) -> bool {
    let mut guard = map.lock().expect("rejected-token log map poisoned");
    let should_log = match guard.get(&ip) {
        Some(last) => now.duration_since(*last) >= REJECTED_TOKEN_LOG_COOLDOWN,
        None => true,
    };
    if should_log {
        guard.insert(ip, now);
    }
    should_log
}

fn log_rejected_token_once(ip: std::net::IpAddr) {
    static LAST_LOGGED: std::sync::OnceLock<Mutex<std::collections::HashMap<std::net::IpAddr, std::time::Instant>>> =
        std::sync::OnceLock::new();
    let map = LAST_LOGGED.get_or_init(|| Mutex::new(std::collections::HashMap::new()));
    if should_log_rejected_token(map, ip, std::time::Instant::now()) {
        eprintln!("aivyx-pa web ui: rejected token from {ip}");
    }
}

